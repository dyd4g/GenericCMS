// Builds public/brand/hplife-preview.css (HP LIFE fonts, base styles and brand variables) from the GenericLMS files, so
// the "content only" preview looks like the learner site. Run from the GenericCMS folder: node scripts/sync-preview-css.cjs
const fs = require('fs'), path = require('path');
const lms = path.resolve(__dirname, '..', '..', 'GenericLMS');
const styles = fs.readFileSync(path.join(lms, 'styles.css'), 'utf8');
const variables = fs.readFileSync(path.join(lms, 'platform', 'brand-variables.css'), 'utf8');
fs.writeFileSync(path.join(__dirname, '..', 'public', 'brand', 'hplife-preview.css'), '/* Generated by scripts/sync-preview-css.cjs. Do not edit by hand. */\n' + variables + '\n' + styles);
console.log('hplife-preview.css written');
